#include <stdint.h>
#include <stdio.h>

int main() {
    // 1. 将数据分配在内存中（作为数组，它们会被分配在栈上或数据段）
    uint32_t inputs[4]  = {2, 3, 4, 5};
    uint32_t weights[4] = {-10, -20, -30, -40};
    uint32_t acc        = -1000;

    // 2. 纯手工汇编流水线调度
    asm volatile (
        // ==========================================
        // 第一阶段：访存与 Input 缓存
        // ==========================================
        // 手动从 inputs 数组的内存地址中 Load 数据到临时寄存器 t0~t3
        "lw t0, 0(%[p_in]) \n\t"
        "lw t1, 4(%[p_in]) \n\t"
        "lw t2, 8(%[p_in]) \n\t"
        "lw t3, 12(%[p_in]) \n\t"

        // 发射 buf4，将 t0~t3 的数据打入 CVXIF 协处理器的内部 Buffer
        "buf4 zero, t0, t1, t2, t3 \n\t"

        // ==========================================
        // 第二阶段：访存与矩阵乘加计算
        // ==========================================
        // 为了节省物理寄存器压力，我们直接复用 t0~t3 来 Load Weights
        "lw t0, 0(%[p_w]) \n\t"
        "lw t1, 4(%[p_w]) \n\t"
        "lw t2, 8(%[p_w]) \n\t"
        "lw t3, 12(%[p_w]) \n\t"

        // 发射 mac16buf，进行乘加计算，并把最终结果写回 acc 寄存器
        "mac16buf %[acc], t0, t1, t2, t3 \n\t"

        // ==========================================
        // 约束与通知编译器
        // ==========================================
        // 输出：acc 既是初始输入，也是最终结果写回的载体
        : [acc] "+r" (acc)

        // 输入：把 inputs 和 weights 数组的【首地址（指针）】通过通用寄存器传给汇编
        : [p_in] "r" (inputs),
          [p_w]  "r" (weights)

        // Clobber List (破坏列表)：
        // 极其重要！必须告诉 C 编译器我们在汇编里私自征用了 t0, t1, t2, t3。
        // 这样编译器就不会把主程序里的其他重要变量存放在这四个寄存器里，避免数据被我们覆盖。
        : "t0", "t1", "t2", "t3", "memory"
    );

    // 3. 检查硬件返回结果
    if (acc == 1400) {
        printf("Test PASSED! Hardware Result = %d\n", acc);
        return 0;
    } else {
        printf("Test FAILED! Expected 1400, got %d\n", acc);
        return 1;
    }
}